"""
build_diagrams.py — построение диаграмм практик №3–№6 в SVG и PNG.

Запуск:  python tools/build_diagrams.py            (из корня репозитория)
Результат: diagrams/*.svg и images/*.png

Трассировка связей ортогональная; порядок «дорожек» (lanes) подобран так,
чтобы пересечений не было там, где это топологически возможно.
"""
from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from gfx import Scene, render_svg, measure, wrap  # noqa: E402
import shapes as S                            # noqa: E402
import data as D                              # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SVG_DIR = os.path.join(ROOT, "diagrams")
PNG_DIR = os.path.join(ROOT, "images")


def _out(name):
    return os.path.join(SVG_DIR, name), os.path.join(PNG_DIR, name)


def emit(scene: Scene, name: str, png_scale=2.0):
    """Сохраняет diagrams/<name>.svg и images/<name>.png."""
    os.makedirs(SVG_DIR, exist_ok=True)
    os.makedirs(PNG_DIR, exist_ok=True)
    svg_path = os.path.join(SVG_DIR, name + ".svg")
    with open(svg_path, "w", encoding="utf-8") as f:
        f.write(render_svg(scene))
    from gfx import render_png
    render_png(scene, os.path.join(PNG_DIR, name + ".png"), scale=png_scale)
    print(f"  {name}: svg + png ({scene.width:.0f}x{scene.height:.0f})")


